-- Invented table/function shapes for the development API. No private baseline.
CREATE TABLE public.schedule_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title text NOT NULL,
 start_time time NOT NULL, end_time time, timezone text NOT NULL DEFAULT 'Asia/Kolkata',
 recurrence text NOT NULL DEFAULT 'once', event_date date, enabled boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE public.recurrence_rules (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id bigint NOT NULL UNIQUE REFERENCES public.schedule_events,
 calendar_system text NOT NULL, frequency text NOT NULL, interval_count int NOT NULL, start_date date NOT NULL,
 until_date date, weekdays smallint[], month_days smallint[], months smallint[], hindu_rule jsonb, rule_options jsonb,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE public.schedule_change_requests (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, action text NOT NULL, event_id bigint REFERENCES public.schedule_events,
 requested_by bigint NOT NULL, proposed_data jsonb NOT NULL, status text NOT NULL DEFAULT 'pending',
 created_at timestamptz NOT NULL DEFAULT now(), decided_at timestamptz);
CREATE TABLE public.reminder_deliveries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id bigint NOT NULL REFERENCES public.schedule_events,
 occurrence_date date NOT NULL, status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sent','failed')),
 claimed_at timestamptz, sent_at timestamptz, error_message text, UNIQUE(event_id,occurrence_date));
CREATE FUNCTION public.validate_schedule_proposal(p_data jsonb) RETURNS TABLE(valid boolean,message text)
 LANGUAGE sql AS $$SELECT p_data ?& ARRAY['title','start_time','timezone','recurrence_rule'], 'invented shape fixture'::text$$;
CREATE FUNCTION public.process_schedule_decision(p_request_id bigint,p_user_id bigint,p_decision text,p_force boolean)
 RETURNS TABLE(success boolean,message text) LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'Legacy fixture only'; END$$;
CREATE FUNCTION public.create_schedule_change_proposal(p_action text,p_event_id bigint,p_user_id bigint,p_title text,p_start time,p_end time)
 RETURNS bigint LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'Legacy fixture only'; END$$;
CREATE FUNCTION public.sync_legacy_recurrence_rule() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO recurrence_rules(event_id,calendar_system,frequency,interval_count,start_date)
 VALUES(NEW.id,'gregorian','once',1,NEW.event_date) ON CONFLICT(event_id) DO NOTHING;
 RETURN NEW;
END $$;
CREATE TRIGGER synthetic_sync AFTER INSERT ON public.schedule_events
 FOR EACH ROW EXECUTE FUNCTION public.sync_legacy_recurrence_rule();
